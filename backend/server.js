// server.js
require('dotenv').config();
const express = require('express');
const bodyParser = require('body-parser');
const cors = require('cors');
const path = require('path');
const { Pool } = require('pg');

const app = express();
app.use(cors());
app.use(bodyParser.json());
app.use(express.static(path.join(__dirname, '..', 'public'))); // note: public is one level up

// Pool using DATABASE_URL (Supabase or other). For local testing without SSL, this will be false.
const pool = new Pool({
  connectionString: process.env.DATABASE_URL || process.env.PG_CONNECTION_STRING || null,
  ssl: process.env.NODE_ENV === 'production' ? { rejectUnauthorized: false } : false,
});

// ADMIN password handling:
// If ADMIN_PASSWORD is not set, we default to 'admin123' (backwards compatibility).
const ADMIN_PASSWORD = process.env.ADMIN_PASSWORD || 'admin123';
if (!process.env.ADMIN_PASSWORD) {
  console.warn('WARNING: no ADMIN_PASSWORD env var set — using default admin password "admin123". Set ADMIN_PASSWORD in production!');
}

const requireAdmin = (req, res, next) => {
  const header = (req.headers['admin-password'] || '').toString();
  if (header && header === ADMIN_PASSWORD) return next();
  return res.status(403).json({ error: 'admin auth required' });
};

/**
 * Initialize DB: create tables if missing.
 * This runs once at server start.
 */
async function initDb() {
  // If no pool connection string provided, log and continue (you can use local Postgres)
  if (!pool.options || !pool.options.connectionString) {
    console.warn('No DATABASE_URL provided. Please set DATABASE_URL to use Postgres. The server will still run, but DB operations will fail.');
    return;
  }

  const createTablesSQL = `
  CREATE TABLE IF NOT EXISTS books (
    book_id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    author TEXT,
    category TEXT,
    status TEXT NOT NULL DEFAULT 'Available'
  );

  CREATE TABLE IF NOT EXISTS borrow_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id TEXT REFERENCES books(book_id) ON DELETE CASCADE,
    borrower_name TEXT,
    borrowed_at TIMESTAMPTZ DEFAULT now(),
    returned_at TIMESTAMPTZ
  );
  `;

  try {
    await pool.query(createTablesSQL);
    console.log('Database initialized (tables exist).');
  } catch (err) {
    console.error('Error initializing database:', err);
    // don't throw — keep server running so dev can see logs
  }
}

/* ---- API endpoints ---- */

/* GET /api/books?search=&category=&status=&book_id=
   Returns books and also includes the latest borrow info (borrower_name, borrowed_at) if any.
*/
app.get('/api/books', async (req, res) => {
  try {
    const { search, category, status, book_id } = req.query;
    // base: include latest borrow info via lateral join
    let q = `
      SELECT b.*,
             br.borrower_name,
             br.borrowed_at
      FROM books b
      LEFT JOIN LATERAL (
        SELECT borrower_name, borrowed_at
        FROM borrow_records
        WHERE book_id = b.book_id
        ORDER BY borrowed_at DESC
        LIMIT 1
      ) br ON true
    `;
    const cond = [];
    const vals = [];
    if (book_id) { vals.push(book_id); cond.push(`b.book_id = $${vals.length}`); }
    if (category) { vals.push(category); cond.push(`b.category = $${vals.length}`); }
    if (status) { vals.push(status); cond.push(`b.status = $${vals.length}`); }
    if (search) { vals.push(`%${search}%`); cond.push(`(b.title ILIKE $${vals.length} OR b.author ILIKE $${vals.length} OR b.book_id ILIKE $${vals.length})`); }
    if (cond.length) q += ' WHERE ' + cond.join(' AND ');
    q += ' ORDER BY b.title ASC';
    const { rows } = await pool.query(q, vals);
    res.json(rows);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'server error' });
  }
});

/* POST /api/books (add or update) - admin */
app.post('/api/books', requireAdmin, async (req, res) => {
  try {
    const { book_id, title, author, category } = req.body;
    if (!book_id || !title) return res.status(400).json({ error: 'book_id and title required' });
    const q = `
      INSERT INTO books (book_id, title, author, category, status)
      VALUES ($1,$2,$3,$4,'Available')
      ON CONFLICT (book_id) DO UPDATE SET title=EXCLUDED.title, author=EXCLUDED.author, category=EXCLUDED.category
      RETURNING *;
    `;
    const { rows } = await pool.query(q, [book_id, title, author || '', category || '']);
    res.json(rows[0]);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'server error' });
  }
});

/* DELETE /api/books/:book_id - admin */
app.delete('/api/books/:book_id', requireAdmin, async (req, res) => {
  const client = await pool.connect();
  try {
    const { book_id } = req.params;
    await client.query('BEGIN');
    await client.query('DELETE FROM borrow_records WHERE book_id = $1', [book_id]);
    const { rowCount } = await client.query('DELETE FROM books WHERE book_id = $1', [book_id]);
    await client.query('COMMIT');
    if (!rowCount) return res.status(404).json({ error: 'book not found' });
    res.json({ success: true });
  } catch (err) {
    await client.query('ROLLBACK').catch(()=>{});
    console.error(err);
    res.status(500).json({ error: 'server error' });
  } finally {
    client.release();
  }
});

/* Borrow a book */
app.post('/api/books/borrow', async (req, res) => {
  const client = await pool.connect();
  try {
    const { book_id, borrower_name } = req.body;
    if (!book_id || !borrower_name) return res.status(400).json({ error: 'book_id and borrower_name required' });
    const { rows } = await client.query('SELECT status FROM books WHERE book_id = $1', [book_id]);
    if (!rows.length) return res.status(404).json({ error: 'book not found' });
    if (rows[0].status !== 'Available') return res.status(400).json({ error: 'book not available' });

    await client.query('BEGIN');
    await client.query('UPDATE books SET status = $1 WHERE book_id = $2', ['Borrowed', book_id]);
    await client.query('INSERT INTO borrow_records (book_id, borrower_name) VALUES ($1,$2)', [book_id, borrower_name]);
    await client.query('COMMIT');
    res.json({ success: true });
  } catch (err) {
    await client.query('ROLLBACK').catch(()=>{});
    console.error(err);
    res.status(500).json({ error: 'server error' });
  } finally {
    client.release();
  }
});

/* Return a book */
app.post('/api/books/return', async (req, res) => {
  const client = await pool.connect();
  try {
    const { book_id } = req.body;
    if (!book_id) return res.status(400).json({ error: 'book_id required' });
    const { rows } = await client.query('SELECT id FROM borrow_records WHERE book_id = $1 AND returned_at IS NULL ORDER BY borrowed_at DESC LIMIT 1', [book_id]);
    if (!rows.length) return res.status(400).json({ error: 'book not currently borrowed' });
    const id = rows[0].id;

    await client.query('BEGIN');
    await client.query('UPDATE borrow_records SET returned_at = now() WHERE id = $1', [id]);
    await client.query('UPDATE books SET status = $1 WHERE book_id = $2', ['Available', book_id]);
    await client.query('COMMIT');
    res.json({ success: true });
  } catch (err) {
    await client.query('ROLLBACK').catch(()=>{});
    console.error(err);
    res.status(500).json({ error: 'server error' });
  } finally {
    client.release();
  }
});

/* List currently borrowed books */
app.get('/api/borrowed-books', async (req, res) => {
  try {
    const { rows } = await pool.query(`
      SELECT br.*, b.title, b.author
      FROM borrow_records br
      JOIN books b ON br.book_id = b.book_id
      WHERE br.returned_at IS NULL
      ORDER BY br.borrowed_at DESC
    `);
    res.json(rows);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'server error' });
  }
});

/* Backup (admin) */
app.post('/api/backup-migrate', requireAdmin, async (req, res) => {
  try {
    await pool.query('CREATE TABLE IF NOT EXISTS borrow_records_backup AS TABLE borrow_records WITH NO DATA');
    await pool.query('INSERT INTO borrow_records_backup SELECT * FROM borrow_records');
    res.json({ success: true });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'server error' });
  }
});

/* serve SPA: catch-all for non-API routes (Express v5 compatible) */
// Serve index.html for any route not starting with /api
app.get(/^(?!\/api).*/, (req, res) => {
  res.sendFile(path.join(__dirname, '..', 'public', 'index.html'));
});

// Start
const PORT = process.env.PORT || 3000;
(async () => {
  await initDb();
  app.listen(PORT, () => console.log(`Server running on ${PORT}`));
})();
